#!/usr/bin/env python3
# 在 rmz4 ROM 里定位"图形表"(rmz3 的 struct ColorGraphic[] = Graphic12+Palette8 = 20 字节/条),
# 全量导出成 rmz3 风格的 src/data/graphic_table/:
#   - 每张表一个 <name>.s: 描述符条目(自相对 src 用 ROM 原值, 注释标出目标) + 底部 .incbin blob 标签
#   - blobs/<ADDR>.bin / .pal: 从 ROM 按 descriptor 的 size/psize 精确切出的字节(LZ77 压缩态原样保留)
#   - manifest.json: 表清单
# 字节忠实: descriptor 的非指针字段与 src 自相对值都按 ROM 原值落地; blob 是 ROM 精确切片。
# (rmz3 那种 `LABEL-.` 符号化需要整 ROM linker 布局, 这里先做可独立验证的等价形式。)
import os, json, struct

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
ROM  = open(os.path.join(ROOT, "Rockman Zero 4.gba"), "rb").read()
BASE = 0x08000000
N    = len(ROM)
OUT  = os.path.join(ROOT, "src", "data", "graphic_table")
BLOB = os.path.join(OUT, "blobs")

def u16(o): return ROM[o] | (ROM[o+1] << 8)
def u32(o): return int.from_bytes(ROM[o:o+4], "little")
def s32(o):
    v = u32(o); return v - 0x100000000 if v >= 0x80000000 else v

PROP_BAD = ~0x1027 & 0xFFFF   # 允许位: MAP2D(1) LZ77(2) NO_PAL(4) BPP4(0x20) RLU(0x1000)

def entry_ok(o):
    if o + 20 > N: return False
    tgt = BASE + o + s32(o)
    if not (BASE <= tgt < BASE + N): return False
    w = u32(o + 4); size = w & 0x3FFFFF; dst = w >> 22
    if size == 0 or size > 0x180000 or dst >= 1024: return False
    props = u16(o + 0x0A)
    if (props & PROP_BAD) or not (props & 0x20): return False
    ptgt = BASE + o + 0x0C + s32(o + 0x0C)
    if not (BASE <= ptgt < BASE + N): return False
    psize = u16(o + 0x10)
    if psize > 0x800 or (psize & 1): return False
    if ROM[o + 0x12] > 1 or ROM[o + 0x13] >= 64: return False
    return True

def find_tables(min_run=4):
    runs = []; o = 0; claimed = set()
    while o + 20 <= N:
        if o not in claimed and entry_ok(o):
            p = o; cnt = 0
            while entry_ok(p):
                cnt += 1; p += 20
            if cnt >= min_run:
                runs.append((BASE + o, cnt))
                for q in range(o, p, 20): claimed.add(q)
                o = p; continue
        o += 4
    runs.sort()
    return runs

def parse_entry(o):
    w = u32(o + 4); psize = u16(o + 0x10)
    return dict(
        gfx   = BASE + o + s32(o),       gfx_off = s32(o),
        size  = w & 0x3FFFFF,            dst = w >> 22,
        rowsize = u16(o + 8),            props = u16(o + 0x0A),
        pal   = BASE + o + 0x0C + s32(o + 0x0C), pal_off = s32(o + 0x0C),
        psize = psize, plz = ROM[o + 0x12], pdst = ROM[o + 0x13],
    )

def prop_str(p):
    f = []
    if p & 1:      f.append("MAP2D")
    if p & 2:      f.append("LZ77")
    if p & 4:      f.append("NO_PAL")
    if p & 0x20:   f.append("BPP4")
    if p & 0x1000: f.append("RLU")
    return "|".join(f) if f else "0"

HEADER = """\
@ Auto-extracted rmz4 graphic table (struct ColorGraphic[] = Graphic(12)+Palette(8) = 20B/entry)
@ Table base 0x{base:08X}, {count} entries.  Generated by tools/export_graphic_tables.py
@ Flags: MAP2D=0x1 LZ77=0x2 NO_PAL=0x4 BPP4=0x20 RLU=0x1000
@ src/palsrc 4byte 值为 ROM 原始自相对偏移(= 目标地址 - 该字段地址), 注释里给出绝对目标。
.section .rodata
.balign 4, 0

.global gGraphicTable_{base:08X}
gGraphicTable_{base:08X}:
"""

def export():
    os.makedirs(BLOB, exist_ok=True)
    tables = find_tables()
    blob_written = {}    # addr -> (filename, length)
    def write_blob(addr, length, ext):
        if length <= 0: return None
        key = (addr, length)
        if key in blob_written: return blob_written[key][0]
        off = addr - BASE
        data = ROM[off:off+length]
        fn = "%08X.%s" % (addr, ext)
        with open(os.path.join(BLOB, fn), "wb") as f: f.write(data)
        blob_written[key] = (fn, length)
        return fn

    manifest = []
    desc_bytes_ok = True
    for base, count in tables:
        o0 = base - BASE
        lines = [HEADER.format(base=base, count=count)]
        # 数据标签收集: (label, filename)
        data_lines = ["\n@ ===================== blobs =====================\n"]
        seen_label = set()
        for i in range(count):
            o = o0 + i * 20
            e = parse_entry(o)
            gfn = write_blob(e["gfx"], e["size"], "bin")
            pfn = write_blob(e["pal"], e["psize"], "pal") if e["psize"] > 0 else None
            glabel = "blob_%08X" % e["gfx"]
            lines.append("\t@ Graphic %d" % i)
            lines.append("\t.4byte 0x%08X \t@ src -> 0x%08X (%s)" % (e["gfx_off"] & 0xFFFFFFFF, e["gfx"], glabel))
            lines.append("\t.4byte %d | (%d << 22) \t@ size | dst<<22" % (e["size"], e["dst"]))
            lines.append("\t.2byte %d, 0x%04X \t@ rowsize, props {%s}" % (e["rowsize"], e["props"], prop_str(e["props"])))
            if e["psize"] > 0:
                plabel = "blob_%08X" % e["pal"]
                lines.append("\t\t.4byte 0x%08X \t@ palsrc -> 0x%08X (%s)" % (e["pal_off"] & 0xFFFFFFFF, e["pal"], plabel))
            else:
                lines.append("\t\t.4byte 0x%08X \t@ palsrc -> 0x%08X (psize 0)" % (e["pal_off"] & 0xFFFFFFFF, e["pal"]))
            lines.append("\t\t.2byte %d \t@ pal bytesize" % e["psize"])
            lines.append("\t\t.byte %d, %d \t@ lz77, pal dst\n" % (e["plz"], e["pdst"]))
            # data labels
            if gfn and glabel not in seen_label:
                data_lines.append("%s: .incbin \"blobs/%s\"" % (glabel, gfn)); seen_label.add(glabel)
            if pfn:
                plabel = "blob_%08X" % e["pal"]
                if plabel not in seen_label:
                    data_lines.append("%s: .incbin \"blobs/%s\"" % (plabel, pfn)); seen_label.add(plabel)
            # 自校验: 重编码 descriptor 20 字节 == ROM
            rec = struct.pack("<iIHHiHBB",
                e["gfx_off"], (e["size"] | (e["dst"] << 22)) & 0xFFFFFFFF,
                e["rowsize"], e["props"], e["pal_off"], e["psize"], e["plz"], e["pdst"])
            if rec != ROM[o:o+20]:
                desc_bytes_ok = False
                print("  !! descriptor mismatch @0x%08X entry %d" % (base, i))
        name = "table_%08X.s" % base
        with open(os.path.join(OUT, name), "w", encoding="utf-8") as f:
            f.write("\n".join(lines) + "\n".join(data_lines) + "\n")
        manifest.append(dict(base="0x%08X" % base, count=count, file=name))

    with open(os.path.join(OUT, "manifest.json"), "w", encoding="utf-8") as f:
        json.dump(dict(rom_sha1="d60d6be4...", tables=manifest,
                       blob_count=len(blob_written),
                       blob_bytes=sum(l for _, l in blob_written.values())), f, indent=1)
    print("tables: %d   blobs: %d (%d bytes)   descriptor round-trip: %s" % (
        len(tables), len(blob_written), sum(l for _, l in blob_written.values()),
        "OK" if desc_bytes_ok else "FAIL"))
    return tables

if __name__ == "__main__":
    export()
