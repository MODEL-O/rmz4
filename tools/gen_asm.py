#!/usr/bin/env python3
# 字节一致 asm 生成器。输入: archive/code_c/code.bin.units.tsv (Ghidra 权威代码单元地图)
# 输出: archive/code_asm/code.s  (单一汇编单元, .org 排到真实偏移)
# 策略:
#   * 把"同模式连续指令"聚成 run, 整段交给 objdump 取可回编译助记符(PC 相对、bl 绝对地址);
#   * 数据单元(字面量池/跳表)出 .byte, 不反汇编;
#   * 全程序一个汇编单元 => 所有内部 bl/b 在汇编期解析 => 字节一致;
#   * 末尾: 汇编 + objcopy + 与 code.bin 逐字节比对; 不符的指令回退为 .byte, 迭代。
import subprocess, os, re, sys, hashlib

ROOT = r"E:\GameProjects\rmz3\rmz4-dev"
TC   = r"E:\GameProjects\rmz3\toolchain\arm\xpack-arm-none-eabi-gcc-15.2.1-1.1\bin"
OBJDUMP = os.path.join(TC, "arm-none-eabi-objdump.exe")
AS      = os.path.join(TC, "arm-none-eabi-as.exe")
LD      = os.path.join(TC, "arm-none-eabi-ld.exe")
OBJCOPY = os.path.join(TC, "arm-none-eabi-objcopy.exe")
BIN   = os.path.join(ROOT, "archive", "code.bin")
TSV   = os.path.join(ROOT, "archive", "code_c", "code.bin.units.tsv")
OUTD  = os.path.join(ROOT, "archive", "code_asm")
SP    = os.path.join(OUTD, "code.s")
OP    = os.path.join(OUTD, "code.o")
BP    = os.path.join(OUTD, "code.bin")

def load_units():
    units = []
    with open(TSV) as f:
        for line in f:
            line = line.rstrip("\n")
            if not line: continue
            off, ln, kind, mode, hx = line.split("\t")
            units.append([int(off,16), int(ln), kind, mode, hx])
    units.sort(key=lambda u: u[0])
    # 规整为文件相对偏移 (清单里带 imageBase 0x08000000)
    base = units[0][0]
    for u in units:
        u[0] -= base
    return units

def objdump_run(start, stop, thumb):
    args = [OBJDUMP, "-b","binary","-m","armv4t",
            "-M", "force-thumb" if thumb else "no-force-thumb",
            "-D", f"--start-address=0x{start:x}", f"--stop-address=0x{stop:x}", BIN]
    out = subprocess.run(args, capture_output=True, text=True).stdout
    res = {}  # addr -> (mnem_text, nbytes)
    for line in out.splitlines():
        if "\t" not in line: continue
        head, *rest = line.split("\t")
        m = re.match(r"\s*([0-9a-fA-F]+):\s*$", head)
        if not m or not rest: continue
        addr = int(m.group(1),16)
        bytefield = rest[0].strip()
        mnem = rest[1].strip() if len(rest)>1 else ""
        ops  = rest[2].strip() if len(rest)>2 else ""
        ops = ops.split("@")[0].strip()
        nb = len(bytefield.split())*2
        txt = mnem if not ops else f"{mnem} {ops}"
        res[addr] = (txt, nb)
    return res

def build_runs(units):
    # 把连续的同模式 I 单元聚成 run; D 单元单独成块
    blocks = []  # (kind, mode, start, end_units_list)
    i = 0
    while i < len(units):
        off,ln,kind,mode,hx = units[i]
        if kind == "I":
            j = i
            run = []
            while j < len(units) and units[j][2]=="I" and units[j][3]==mode:
                # 必须地址连续
                if run and units[j][0] != run[-1][0]+run[-1][1]:
                    break
                run.append(units[j]); j += 1
            blocks.append(("I", mode, run))
            i = j
        else:
            blocks.append(("D", "-", [units[i]]))
            i += 1
    return blocks

def emit(units, fallback):
    blocks = build_runs(units)
    out = [".syntax unified", "@ auto-generated byte-exact reassembly of code.bin",
           ".section .text,\"ax\",%progbits", ".thumb", ""]
    cur_mode = "T"
    prev_ins = None  # 上一条指令的偏移 (用于定位 .org 后退错误的真凶)
    for kind, mode, run in blocks:
        if kind == "I":
            if mode != cur_mode:
                out.append(".arm" if mode=="A" else ".thumb")
                cur_mode = mode
            start = run[0][0]; stop = run[-1][0] + run[-1][1]
            dis = objdump_run(start, stop, thumb=(mode=="T"))
            for off,ln,k,md,hx in run:
                # 每条指令前 .org 钉到绝对偏移: 杜绝某条编码长度不符引发的级联错位
                tag = f"@prev {prev_ins:08x}" if prev_ins is not None else "@prev start"
                out.append(f".org 0x{off:x}\t{tag}")
                if off in fallback or off not in dis or dis[off][1] != ln:
                    bs = ",".join("0x"+hx[i:i+2] for i in range(0,len(hx),2))
                    out.append(f"\t.byte {bs}\t@ {off:08x} (raw)")
                else:
                    out.append(f"\t{dis[off][0]}\t@ {off:08x} {hx}")
                prev_ins = off
        else:
            off,ln,k,md,hx = run[0]
            out.append(f".org 0x{off:x}")
            bs = ",".join("0x"+hx[i:i+2] for i in range(0,len(hx),2))
            out.append(f"\t.byte {bs}\t@ {off:08x} data")
    return "\n".join(out)+"\n"

LDS = os.path.join(OUTD, "code.ld")
EP  = os.path.join(OUTD, "code.elf")

def assemble(src):
    os.makedirs(OUTD, exist_ok=True)
    with open(SP,"w") as f: f.write(src)
    with open(LDS,"w") as f:
        f.write("SECTIONS { . = 0x0; .text : { *(.text) } /DISCARD/ : { *(*) } }\n")
    r = subprocess.run([AS,"-mcpu=arm7tdmi","-o",OP,SP], capture_output=True, text=True)
    if r.returncode != 0:
        return None, r.stderr
    # 链接到基址 0, 解析所有 bl/b 绝对地址引用 (objcopy 本身不链接)
    rl = subprocess.run([LD,"-T",LDS,"-o",EP,OP], capture_output=True, text=True)
    if rl.returncode != 0:
        return None, rl.stderr
    subprocess.run([OBJCOPY,"-O","binary",EP,BP], check=True)
    return open(BP,"rb").read(), r.stderr

def offsets_from_errors(err):
    # 从 AS 报错的行号定位源码行, 取该行 "@ XXXXXXXX" 注释里的偏移
    srclines = open(SP).read().splitlines()
    offs = set()
    for m in re.finditer(r"code\.s:(\d+):\s*Error", err):
        ln = int(m.group(1))-1
        if 0 <= ln < len(srclines):
            s = srclines[ln]
            # .org 后退错误: 真凶是该行 @prev 标的上一条指令
            mm = re.search(r"@prev ([0-9a-fA-F]{8})", s)
            if not mm:
                mm = re.search(r"@ ([0-9a-fA-F]{8})", s)
            if mm: offs.add(int(mm.group(1),16))
    return offs

def main():
    units = load_units()
    print(f"units={len(units)}")
    orig = open(BIN,"rb").read()
    fallback = set()
    for it in range(40):
        src = emit(units, fallback)
        data, err = assemble(src)
        if data is None:
            offs = offsets_from_errors(err)
            new = offs - fallback
            print(f"[iter {it}] AS errors -> +{len(new)} fallback (total {len(fallback)+len(new)})")
            if not new:
                print("AS FAIL 无法定位:\n"+err[:3000]); return
            fallback |= offs
            continue
        # 截到 code.bin 长度
        data = data[:len(orig)]
        if len(data) < len(orig):
            data = data + b"\x00"*(len(orig)-len(data))
        if data == orig:
            print(f"[iter {it}] BYTE-EXACT OK  sha1={hashlib.sha1(data).hexdigest()}  fallback={len(fallback)}")
            with open(os.path.join(OUTD,"OK.txt"),"w") as f:
                f.write(f"byte-exact, fallback insns={len(fallback)}\n")
            with open(os.path.join(OUTD,"fallback.txt"),"w") as f:
                for o in sorted(fallback): f.write(f"{o:08x}\n")
            return
        # 找出不一致字节 -> 映射回所属指令单元 -> 加入回退
        new_fb = 0
        idx = {u[0]:u for u in units}
        # 建立 offset->unit 起点 查找
        starts = sorted(idx)
        import bisect
        diffs = [i for i in range(len(orig)) if data[i]!=orig[i]]
        print(f"[iter {it}] diffs={len(diffs)} fallback={len(fallback)}")
        for d in diffs:
            p = bisect.bisect_right(starts, d)-1
            u0 = starts[p]; u = idx[u0]
            if u[2]=="I" and u0 not in fallback:
                fallback.add(u0); new_fb += 1
        if new_fb == 0:
            print("  无新增回退但仍不一致, 打印前几处:")
            for d in diffs[:20]:
                print(f"   @0x{d:08x} got {data[d]:02x} want {orig[d]:02x}")
            return
    print("迭代上限仍未一致")

if __name__ == "__main__":
    main()
