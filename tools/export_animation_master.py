#!/usr/bin/env python3
# 导出 rmz4 的"动画表", 对齐 rmz3 src/data/animation + sprites/ 的组织方式:
#   sprite_static.s  : gStaticMotionMetaspriteTable[248] @ 0x08C1C000
#                    + gStaticMotionCmdTable[248]        @ 0x08C3C000
#   sprite_dynamic.s : gDynamicMotionMetaspriteTable[209] @ 0x088A7000
#                    + gDynamicMotionCmdTable[209]        @ 0x088C7000
#   (palette.c 的调色板动画表见 export_palette_animation.py)
#
# rmz3 布局(本脚本照搬): 每个 motion 一个目录, 里面 inc 与 json 并排:
#   src/data/graphic_table/sprites/<static|dynamic>/<id>/
#       metasprite.inc   <- 由 metasprite.json 生成的汇编(独立 section + label gMetaSprite_<type>_<id>)
#       metasprite.json  <- 真源(canonical source)
#       sequence.inc     <- gAnimationSequence_<type>_<id>
#       sequence.json
#       sheet.* / *.4bpp ...(图形导出器产出)
#   多个 motion 共享同一块时, 只有最小 id(canonical)产出真 inc, 其余写共享说明 stub。
#   主表 sprite_<type>.s = 两张 .word 指针表(按 label 引用) + .include 各 canonical inc。
#
# 结构(同 rmz3 include/motion.h, animation.h):
#   MetaspriteHeader(4B) = { u16 ofs, s8 subspriteCount, u8 sheetIdx };
#     子精灵地址 = 块起点 + ofs  (块相对! 不是字段相对)
#   Subsprite(4B)        = { u16{tileNum:10,xflip:1,yflip:1,size:2,shape:2}, s8 x, s8 y }
#   AnimScript[] (AnimCmd**) ; AnimCmd(2B) = { u8 frameIdx(param), u8 duration(frame; 255 终端 254 goto) }
#
# 字节忠实(全解码, 无 .incbin/.bin): 每块独立命名 section, 由 data/animation.ld 放到各自 ROM 基址,
#   .word/.4byte .±delta 链接后逐区 == ROM。
import os, json
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
ROM  = open(os.path.join(ROOT, "Rockman Zero 4.gba"), "rb").read()
BASE = 0x08000000
N    = len(ROM)
OUT  = os.path.join(ROOT, "src", "data", "animation")
SPR_REL = "src/data/graphic_table/sprites"            # 仓库根相对(给 .include / 路径)
SPR  = os.path.join(ROOT, *SPR_REL.split("/"))        # 与 sheet 同目录放 inc+json

def u16(o): return ROM[o] | (ROM[o+1] << 8)
def u32(o): return int.from_bytes(ROM[o:o+4], "little")
def s8(o):
    v = ROM[o]; return v - 256 if v >= 128 else v

# GBA OBJ 尺寸表: (shape, size) -> (w, h)
OBJ_DIM = {
    (0,0):(8,8),  (0,1):(16,16), (0,2):(32,32), (0,3):(64,64),   # square
    (1,0):(16,8), (1,1):(32,8),  (1,2):(32,16), (1,3):(64,32),   # horizontal
    (2,0):(8,16), (2,1):(8,32),  (2,2):(16,32), (2,3):(32,64),   # vertical
}

# ---------- metasprite 解码 (块相对) ----------
def parse_metasprite(p, bound):
    mp = p - BASE; f0 = u16(mp)
    frames = []
    if f0 == 0 or f0 % 4 or p + f0 > bound:
        return frames, p
    nf = f0 // 4; end = p
    for k in range(nf):
        ho = mp + k * 4
        ofs = u16(ho); sc = ROM[ho + 2]; sheet = ROM[ho + 3]
        sub0 = p + ofs                              # 块相对
        subs = []
        for s in range(sc):
            so = sub0 - BASE + s * 4
            attr = u16(so)
            size = (attr >> 12) & 3; shape = (attr >> 14) & 3
            w, h = OBJ_DIM.get((shape, size), (0, 0))
            subs.append(dict(tileNum=attr & 0x3FF, xflip=bool((attr >> 10) & 1),
                             yflip=bool((attr >> 11) & 1), size=[w, h],
                             x=s8(so + 2), y=s8(so + 3)))
        end = max(end, sub0 + sc * 4)
        frames.append(dict(sheetIdx=sheet, subsprites=subs))
    return frames, end

# ---------- sequence(AnimCmd 脚本) 解码 (两级) ----------
def parse_cmd(p, bound):
    sp = p - BASE; s0 = u32(sp)
    if not (p < s0 <= bound) or (s0 - p) % 4:
        return [], p
    nscript = (s0 - p) // 4
    scripts = []; end = p
    for k in range(nscript):
        ap = u32(sp + k * 4)
        if not (BASE <= ap < bound):
            scripts.append(None); continue
        ao = ap - BASE; cmds = []; j = 0
        while j < 512:
            frameIdx = ROM[ao + j * 2]; dur = ROM[ao + j * 2 + 1]
            cmds.append(dict(frameIdx=frameIdx, duration=dur))
            end = max(end, ap + (j + 1) * 2)
            if dur >= 254:        # 255 终端 / 254 goto
                break
            j += 1
        scripts.append(cmds)
    return scripts, end

def region_end(tab, cnt, parse, align=4):
    end = 0
    for i in range(cnt):
        p = u32(tab - BASE + i * 4)
        bound = u32(tab - BASE + (i + 1) * 4) if i + 1 < cnt else (BASE + N)
        if not (BASE <= bound <= BASE + N): bound = BASE + N
        _, e = parse(p, bound)
        end = max(end, e)
    return (end + align - 1) & ~(align - 1)

# ---------- per-motion inc 生成 ----------
INC_HEAD = "@ Generated by tools/export_animation_master.py. DO NOT EDIT!\n@ source: {src}\n"

def metasprite_inc(label, addr, span_to, src):
    L = [INC_HEAD.format(src=src),
         '.section .rodata.%s, "a"' % label, ".balign 4, 0", "",
         ".global %s" % label, "%s:" % label]
    mp = addr - BASE; span = span_to - addr; f0 = u16(mp)
    nf = f0 // 4 if (f0 and f0 % 4 == 0 and f0 <= span) else 0
    for k in range(nf):
        ho = mp + k * 4
        L.append("\t.2byte %d" % u16(ho))
        L.append("\t.byte %d, %d \t@ OAM sprites count, sheet/*.png" % (ROM[ho + 2], ROM[ho + 3]))
    o = mp + nf * 4; rest = span - nf * 4
    if nf:
        L.append("\t@;@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@")
    nsub = rest // 4
    for s in range(nsub):
        so = o + s * 4
        L.append("\t.2byte 0x%04X" % u16(so))
        L.append("\t.byte %d, %d" % (ROM[so + 2], ROM[so + 3]))
    for t in range(rest - nsub * 4):
        L.append("\t.byte %d" % ROM[o + nsub * 4 + t])
    L.append("")
    return "\n".join(L) + "\n"

def sequence_inc(label, addr, span_to, src):
    L = [INC_HEAD.format(src=src),
         '.section .rodata.%s, "a"' % label, ".balign 4, 0", "",
         ".global %s" % label, "%s:" % label]
    sp = addr - BASE; span = span_to - addr; s0 = u32(sp)
    nscript = (s0 - addr) // 4 if (addr < s0 <= span_to and (s0 - addr) % 4 == 0) else 0
    for k in range(nscript):
        field = addr + k * 4; ptr = u32(sp + k * 4)
        L.append("\t.4byte .%+d \t@ script %d" % (ptr - field, k))
    o = sp + nscript * 4; rest = span - nscript * 4
    npair = rest // 2
    for j in range(npair):
        fi = ROM[o + j * 2]; du = ROM[o + j * 2 + 1]
        tag = " (terminal)" if du == 255 else " (goto)" if du == 254 else ""
        L.append("\t.byte %d, %d \t@ frameIdx, duration%s" % (fi, du, tag))
    for t in range(rest - npair * 2):
        L.append("\t.byte %d" % ROM[o + npair * 2 + t])
    L.append("")
    return "\n".join(L) + "\n"

def stub_inc(kind, dupid, canon):
    return ("@ motion %03d 与 motion %03d 共享同一 %s。\n"
            "@ 数据见 ../%03d/%s.inc, 主表按 label 复用其符号。\n"
            % (dupid, canon, kind, canon, kind))

S_HEAD = """\
@ rmz4 animation master: {title}
@ tools/export_animation_master.py 生成。每 motion 一份 metasprite.inc/sequence.inc 与 json 并排,
@ 见 {sprrel}/{key}/<id>/。本表两张指针表按 label 引用, 末尾 .include 各 canonical 块。
@ MetaspriteHeader(4B)={{u16 ofs(块相对),s8 cnt,u8 sheetIdx}}; Subsprite(4B)={{u16 attr,s8 x,s8 y}}
@ AnimCmd(2B)={{u8 frameIdx,u8 duration}} 255 终端 254 goto。
@ 字节真值: 各块独立 section, data/animation.ld 放到各自 ROM 基址后链接。

"""

TABLES = {
    "static":  dict(title="static (gStaticMotion*) 248 motions",
                    typ="Static",
                    meta=("gStaticMotionMetaspriteTable", 0x08C1C000, 248),
                    cmd =("gStaticMotionCmdTable",        0x08C3C000, 248)),
    "dynamic": dict(title="dynamic (gDynamicMotion*) 209 motions",
                    typ="Dynamic",
                    meta=("gDynamicMotionMetaspriteTable", 0x088A7000, 209),
                    cmd =("gDynamicMotionCmdTable",        0x088C7000, 209)),
}

def dedup(tab, cnt):
    """返回 addrs[i], canon_id[addr](最小 id), uniq(按地址升序), span_end[addr]。"""
    addrs = [u32(tab - BASE + i * 4) for i in range(cnt)]
    canon = {}
    for i, a in enumerate(addrs):
        canon.setdefault(a, i)
    uniq = sorted(canon)
    span = {a: (uniq[j + 1] if j + 1 < len(uniq) else None) for j, a in enumerate(uniq)}
    return addrs, canon, uniq, span

# 收集 ld 用的 (label, addr) 段; export_one 填充
LD_SECTIONS = []   # [(name, addr)]

def export_one(key):
    t = TABLES[key]; typ = t["typ"]
    msym, mtab, mcnt = t["meta"]
    csym, ctab, ccnt = t["cmd"]
    mend = region_end(mtab, mcnt, parse_metasprite)
    cend = region_end(ctab, ccnt, parse_cmd)

    m_addrs, m_canon, m_uniq, m_span = dedup(mtab, mcnt)
    c_addrs, c_canon, c_uniq, c_span = dedup(ctab, ccnt)
    mlabel = {a: "gMetaSprite_%s_%03d" % (key, m_canon[a]) for a in m_uniq}
    clabel = {a: "gAnimationSequence_%s_%03d" % (key, c_canon[a]) for a in c_uniq}

    # ---- 主表 .s ----
    S = [S_HEAD.format(title=t["title"], sprrel=SPR_REL, key=key)]
    S.append('.section .rodata.%s, "a"' % msym)
    S.append(".balign 4, 0")
    S.append(".global %s" % msym); S.append("%s:" % msym)
    for i, a in enumerate(m_addrs):
        S.append("\t.word %s \t@ [%d] -> 0x%08X" % (mlabel[a], i, a))
    S.append("")
    S.append('.section .rodata.%s, "a"' % csym)
    S.append(".balign 4, 0")
    S.append(".global %s" % csym); S.append("%s:" % csym)
    for i, a in enumerate(c_addrs):
        S.append("\t.word %s \t@ [%d] -> 0x%08X" % (clabel[a], i, a))
    S.append("")
    S.append("@ ==== per-motion 数据块(各自 section, 由 animation.ld 定位) ====")
    for a in m_uniq:
        S.append('.include "%s/%s/%03d/metasprite.inc"' % (SPR_REL, key, m_canon[a]))
    for a in c_uniq:
        S.append('.include "%s/%s/%03d/sequence.inc"' % (SPR_REL, key, c_canon[a]))
    S.append("")
    open(os.path.join(OUT, "sprite_%s.s" % key), "w", encoding="utf-8").write("\n".join(S) + "\n")

    # ---- 每 motion 目录: inc + json ----
    for i in range(mcnt):
        d = os.path.join(SPR, key, "%03d" % i)
        os.makedirs(d, exist_ok=True)
        ma = m_addrs[i]; mb = m_span[ma] if m_span[ma] is not None else mend
        ca = c_addrs[i]; cb = c_span[ca] if c_span[ca] is not None else cend
        src_m = "%s/%s/%03d/metasprite.json" % (SPR_REL, key, i)
        src_c = "%s/%s/%03d/sequence.json" % (SPR_REL, key, i)
        # metasprite
        if m_canon[ma] == i:
            open(os.path.join(d, "metasprite.inc"), "w", encoding="utf-8").write(
                metasprite_inc(mlabel[ma], ma, mb, src_m))
        else:
            open(os.path.join(d, "metasprite.inc"), "w", encoding="utf-8").write(
                stub_inc("metasprite", i, m_canon[ma]))
        # sequence
        if c_canon[ca] == i:
            open(os.path.join(d, "sequence.inc"), "w", encoding="utf-8").write(
                sequence_inc(clabel[ca], ca, cb, src_c))
        else:
            open(os.path.join(d, "sequence.inc"), "w", encoding="utf-8").write(
                stub_inc("sequence", i, c_canon[ca]))
        # json (rmz3 字段)
        frames, _ = parse_metasprite(ma, mb)
        scripts, _ = parse_cmd(ca, cb)
        json.dump(dict(label=mlabel[ma], data=frames),
                  open(os.path.join(d, "metasprite.json"), "w", encoding="utf-8"), indent=2)
        json.dump(dict(label=clabel[ca], data=scripts),
                  open(os.path.join(d, "sequence.json"), "w", encoding="utf-8"), indent=2)

    # ld 段
    LD_SECTIONS.append((msym, mtab))
    for a in m_uniq: LD_SECTIONS.append((mlabel[a], a))
    LD_SECTIONS.append((csym, ctab))
    for a in c_uniq: LD_SECTIONS.append((clabel[a], a))

    print("  sprite_%s.s: meta[%d] 0x%08X..0x%08X (uniq %d)  cmd[%d] 0x%08X..0x%08X (uniq %d)" %
          (key, mcnt, mtab, mend, len(m_uniq), ccnt, ctab, cend, len(c_uniq)))
    return dict(key=key,
                metasprite=dict(symbol=msym, base="0x%08X" % mtab, count=mcnt,
                                data_end="0x%08X" % mend, uniq=len(m_uniq)),
                cmd=dict(symbol=csym, base="0x%08X" % ctab, count=ccnt,
                         data_end="0x%08X" % cend, uniq=len(c_uniq)),
                regions=dict(meta=[mtab, mend], cmd=[ctab, cend]))

def write_ld():
    """每个命名 section 放到其 ROM 基址, 供字节验证链接。"""
    L = ["/* Generated by tools/export_animation_master.py. 动画块地址布局, 字节验证用。 */",
         "SECTIONS {"]
    for name, addr in sorted(LD_SECTIONS, key=lambda x: x[1]):
        L.append("  . = 0x%08X;" % addr)
        L.append("  .out_%s : { *(.rodata.%s) }" % (name, name))
    L.append("  /DISCARD/ : { *(*) }")
    L.append("}")
    open(os.path.join(OUT, "animation.ld"), "w", encoding="utf-8").write("\n".join(L) + "\n")

def main():
    os.makedirs(OUT, exist_ok=True)
    manifest = [export_one("static"), export_one("dynamic")]
    write_ld()
    mpath = os.path.join(OUT, "manifest.json")
    man = json.load(open(mpath, encoding="utf-8")) if os.path.exists(mpath) else {}
    man["rom"] = "Rockman Zero 4.gba"
    man["tables"] = manifest
    json.dump(man, open(mpath, "w", encoding="utf-8"), indent=1, ensure_ascii=False)
    print("done. animation.ld: %d sections" % len(LD_SECTIONS))

if __name__ == "__main__":
    main()
