#!/usr/bin/env python
"""Generate C struct-array forms of the ColorGraphic[] tables in
src/data/graphic_table/{bg,dialog,sprite_static}.s.

Each .s = a ColorGraphic[N] descriptor table (N*20 bytes, src/palsrc are baked
self-relative integers) followed by a "resources" block of `.incbin` gfx/pal
bodies. We emit `const struct ColorGraphic <sym>[N]` (values read from ROM) and
move the resource block verbatim into <name>_resources.inc (incbin paths
rewritten cwd-relative), pulled back in via inline-asm `.include`. Source order
is preserved with -fno-toplevel-reorder so the table and bodies stay contiguous,
assembling byte-identical to ROM. Run from rmz4-dev root.
"""
import os

BASE = 0x08000000
ROM = open("Rockman Zero 4.gba", "rb").read()
GDIR = "src/data/graphic_table"

TABLES = [
    # (name, symbol, rom_va, count)
    ("bg", "gBackgroundGraphics", 0x08B6C000, 174),
    ("dialog", "gDialogGraphics", 0x08BFC000, 52),
    ("sprite_static", "gStaticMotionGraphics", 0x08C44000, 248),
]


def u16(o):
    return ROM[o] | (ROM[o + 1] << 8)


def u32(o):
    return int.from_bytes(ROM[o:o + 4], "little")


def s32(o):
    v = u32(o)
    return v - 0x100000000 if v & 0x80000000 else v


def hx(v):
    return ("-0x%08X" % -v) if v < 0 else ("0x%08X" % v)


def split_resources(name):
    """Write <name>_resources.inc (resource block, cwd-relative incbin paths)."""
    sp = f"{GDIR}/{name}.s"
    lines = open(sp, encoding="utf-8").read().splitlines()
    mark = next(i for i, l in enumerate(lines) if "resources ===" in l)
    # incbin paths ("sprites/...") are cwd(root)-relative; keep verbatim.
    incp = f"{GDIR}/{name}_resources.inc"
    open(incp, "w", encoding="utf-8").write("\n".join(lines[mark:]) + "\n")
    return incp


def emit(name, sym, va, n):
    o0 = va - BASE
    incp = split_resources(name)
    L = []
    L.append("// Generated by tools/export_graphic_struct_c.py")
    L.append(f"// ColorGraphic[{n}] @ 0x{va:08X} + gfx/pal bodies; byte-identical to ROM.")
    L.append("")
    L.append('#include "global.h"')
    L.append('#include "gfx.h"')
    L.append("")
    L.append(f"const struct ColorGraphic {sym}[{n}] = {{")
    for i in range(n):
        o = o0 + i * 20
        g_src = s32(o)
        packed = u32(o + 4)
        g_size = packed & ((1 << 22) - 1)
        g_ofs = packed >> 22
        g_chunk = u16(o + 8)
        g_props = u16(o + 10)
        p_src = u32(o + 12)
        p_size = u16(o + 16)
        p_lz = ROM[o + 18]
        p_dst = ROM[o + 19]
        L.append(
            f"    {{ {{ {hx(g_src)}, {g_size}, {g_ofs}, {g_chunk}, 0x{g_props:04X} }}, "
            f"{{ 0x{p_src:08X}, {p_size}, {p_lz}, {p_dst} }} }},  // [{i}]")
    L.append("};")
    L.append("")
    L.append("// gfx/pal bodies (resource block of the original .s)")
    L.append(f'__asm__(".section .rodata\\n.include \\"{incp}\\"\\n");')
    L.append("")
    open(f"{GDIR}/{name}.c", "w", encoding="utf-8").write("\n".join(L))
    print(f"wrote {GDIR}/{name}.c: {sym}[{n}] + {incp}")


def main():
    for name, sym, va, n in TABLES:
        emit(name, sym, va, n)


if __name__ == "__main__":
    main()
