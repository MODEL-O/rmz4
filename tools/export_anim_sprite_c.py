#!/usr/bin/env python
"""Generate C forms of animation/sprite_{static,dynamic}.s.

Each .s has two named .rodata pointer tables (AnimCmd**/Metasprite**) followed by
a block of `.include` directives that pull in per-motion canonical blocks, each of
which lives in its OWN named section (.rodata.gMetaSprite_<key>_NNN /
.rodata.gAnimationSequence_<key>_NNN) placed at its ROM base by animation.ld.

We emit:
  - gXxxMetaspriteTable[N] / gXxxCmdTable[N] as C `const void* const []` arrays in
    their named sections (extern body labels), and
  - the per-motion .include block verbatim via inline-asm `.include`.

-fno-toplevel-reorder keeps each table ahead of nothing (bodies carry their own
sections) so each named section assembles, then animation.ld links every section
at its ROM base -> byte-identical to ROM. Run from rmz4-dev root.
"""
import re

ADIR = "src/data/animation"

KEYS = {
    "static": dict(meta="gStaticMotionMetaspriteTable",
                   cmd="gStaticMotionCmdTable", n=248),
    "dynamic": dict(meta="gDynamicMotionMetaspriteTable",
                    cmd="gDynamicMotionCmdTable", n=209),
}


def parse(key, cfg):
    sp = f"{ADIR}/sprite_{key}.s"
    lines = open(sp, encoding="utf-8").read().splitlines()
    i_meta = next(i for i, l in enumerate(lines)
                  if l.startswith(f".section .rodata.{cfg['meta']}"))
    i_cmd = next(i for i, l in enumerate(lines)
                 if l.startswith(f".section .rodata.{cfg['cmd']}"))
    i_body = next(i for i, l in enumerate(lines) if "per-motion" in l)

    def labels(lo, hi):
        out = []
        for l in lines[lo:hi]:
            s = l.strip()
            if s.startswith(".word "):
                out.append(s.split()[1])
        return out

    meta_lbl = labels(i_meta, i_cmd)
    cmd_lbl = labels(i_cmd, i_body)
    assert len(meta_lbl) == cfg["n"], (key, "meta", len(meta_lbl))
    assert len(cmd_lbl) == cfg["n"], (key, "cmd", len(cmd_lbl))

    body_inc = f"{ADIR}/sprite_{key}_bodies.inc"
    open(body_inc, "w", encoding="utf-8").write(
        "\n".join(lines[i_body:]).rstrip() + "\n")
    return meta_lbl, cmd_lbl, body_inc


def emit(key, cfg, meta_lbl, cmd_lbl, body_inc):
    L = []
    L.append("// Generated by tools/export_anim_sprite_c.py")
    L.append(f"// Mirrors animation/sprite_{key}.s: two named-section pointer tables")
    L.append("// + per-motion canonical blocks (own sections). Linked via")
    L.append("// animation.ld -> byte-identical to ROM.")
    L.append("")
    L.append('#include "global.h"')
    L.append("")
    for lab in sorted(set(meta_lbl)):
        L.append(f"extern const u8 {lab}[];")
    L.append(f"const void* const {cfg['meta']}[{cfg['n']}]")
    L.append(f'    __attribute__((section(".rodata.{cfg["meta"]}"))) = {{')
    for i, lab in enumerate(meta_lbl):
        L.append(f"    {lab},  // [{i}]")
    L.append("};")
    L.append("")
    for lab in sorted(set(cmd_lbl)):
        L.append(f"extern const u8 {lab}[];")
    L.append(f"const void* const {cfg['cmd']}[{cfg['n']}]")
    L.append(f'    __attribute__((section(".rodata.{cfg["cmd"]}"))) = {{')
    for i, lab in enumerate(cmd_lbl):
        L.append(f"    {lab},  // [{i}]")
    L.append("};")
    L.append("")
    L.append("// per-motion canonical blocks (own named sections)")
    L.append(f'__asm__(".include \\"{body_inc}\\"\\n");')
    L.append("")
    open(f"{ADIR}/sprite_{key}.c", "w", encoding="utf-8").write("\n".join(L))
    print(f"wrote {ADIR}/sprite_{key}.c + {body_inc} "
          f"({len(set(meta_lbl))} meta / {len(set(cmd_lbl))} cmd uniq labels)")


def main():
    for key, cfg in KEYS.items():
        meta_lbl, cmd_lbl, body_inc = parse(key, cfg)
        emit(key, cfg, meta_lbl, cmd_lbl, body_inc)


if __name__ == "__main__":
    main()
