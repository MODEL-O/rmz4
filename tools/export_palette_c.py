#!/usr/bin/env python
"""Generate C form of src/data/animation/palette.s (mirrors rmz3 palette.c).

palette.s has two named .rodata sections, each = a table followed by its inline
bodies:
  .rodata.gPlttAnimDataOffsets  @ 0x08C0C000 : s32 self-relative offsets[226]
                                               + PlttAnimData bodies
  .rodata.gPlttAnimScriptTable  @ 0x08C18000 : AnimCmd** absolute ptr[226]
                                               + AnimCmd script bodies

We emit:
  - gPlttAnimDataOffsets[226] as a C s32 array (values from ROM; self-relative
    deltas are constants) placed in .rodata.gPlttAnimDataOffsets, then its bodies
    via inline-asm .include.
  - gPlttAnimScriptTable[226] as a C pointer array (extern script labels) placed
    in .rodata.gPlttAnimScriptTable, then its bodies via inline-asm .include.

-fno-toplevel-reorder keeps each table ahead of its body in the same section, so
each section assembles+links byte-identical to its ROM region. Run from rmz4-dev
root.
"""
BASE = 0x08000000
ROM = open("Rockman Zero 4.gba", "rb").read()
ADIR = "src/data/animation"
SP = f"{ADIR}/palette.s"

OFF_VA, OFF_N = 0x08C0C000, 226
SCR_VA, SCR_N = 0x08C18000, 226


def s32(o):
    v = int.from_bytes(ROM[o:o + 4], "little")
    return v - 0x100000000 if v & 0x80000000 else v


def main():
    lines = open(SP, encoding="utf-8").read().splitlines()

    # marker line indices
    i_data_body = next(i for i, l in enumerate(lines) if "PlttAnimData 内联" in l)
    i_scr_sec = next(i for i, l in enumerate(lines)
                     if l.startswith(".section .rodata.gPlttAnimScriptTable"))
    i_scr_body = next(i for i, l in enumerate(lines) if "AnimCmd 脚本内联" in l)

    # script table labels (between table header and body marker)
    labels = []
    for l in lines[i_scr_sec:i_scr_body]:
        s = l.strip()
        if s.startswith(".word "):
            labels.append(s.split()[1])
    assert len(labels) == SCR_N, len(labels)

    # split body .inc files (verbatim)
    data_inc = f"{ADIR}/palette_data.inc"
    scr_inc = f"{ADIR}/palette_script.inc"
    open(data_inc, "w", encoding="utf-8").write(
        "\n".join(lines[i_data_body:i_scr_sec]).rstrip() + "\n")
    open(scr_inc, "w", encoding="utf-8").write(
        "\n".join(lines[i_scr_body:]).rstrip() + "\n")

    L = []
    L.append("// Generated by tools/export_palette_c.py")
    L.append("// Mirrors rmz3 src/data/animation/palette.c. Two named .rodata")
    L.append("// sections; assembles+links byte-identical to ROM "
             "(0x08C0C000, 0x08C18000).")
    L.append("")
    L.append('#include "global.h"')
    L.append("")
    L.append("// ---- .rodata.gPlttAnimDataOffsets @ 0x08C0C000 (self-relative) ----")
    L.append("const s32 gPlttAnimDataOffsets[%d]" % OFF_N)
    L.append('    __attribute__((section(".rodata.gPlttAnimDataOffsets"))) = {')
    o0 = OFF_VA - BASE
    for r in range(0, OFF_N, 6):
        row = ", ".join("0x%08X" % (s32(o0 + 4 * k) & 0xFFFFFFFF)
                        for k in range(r, min(r + 6, OFF_N)))
        L.append(f"    {row},")
    L.append("};")
    L.append("// PlttAnimData bodies (same section)")
    L.append('__asm__(".section .rodata.gPlttAnimDataOffsets\\n'
             '.include \\"%s\\"\\n");' % data_inc)
    L.append("")
    L.append("// ---- .rodata.gPlttAnimScriptTable @ 0x08C18000 (AnimCmd**) ----")
    for lab in labels:
        L.append(f"extern const u8 {lab}[];")
    L.append("const void* const gPlttAnimScriptTable[%d]" % SCR_N)
    L.append('    __attribute__((section(".rodata.gPlttAnimScriptTable"))) = {')
    for i, lab in enumerate(labels):
        L.append(f"    {lab},  // [{i}]")
    L.append("};")
    L.append("// AnimCmd script bodies (same section)")
    L.append('__asm__(".section .rodata.gPlttAnimScriptTable\\n'
             '.include \\"%s\\"\\n");' % scr_inc)
    L.append("")
    open(f"{ADIR}/palette.c", "w", encoding="utf-8").write("\n".join(L))
    print(f"wrote {ADIR}/palette.c + {data_inc} + {scr_inc} "
          f"({len(set(labels))} unique script labels)")


if __name__ == "__main__":
    main()
