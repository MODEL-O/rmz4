#!/usr/bin/env python
"""Generate C form of src/data/graphic_table/sprite_dynamic.s.

Layout: gDynamicMotionGraphicOffsets[209] (self-relative u32 offsets) @
0x088CC000, then a "sets" block of inline Graphic records, then an `.incbin`
resource block. We emit the offset table as `const u32 [...]` (values from ROM)
and pull the rest (sets + resources) back in verbatim via inline-asm `.include`,
keeping source order with -fno-toplevel-reorder so it stays contiguous and
assembles byte-identical to ROM. Run from rmz4-dev root.
"""
BASE = 0x08000000
ROM = open("Rockman Zero 4.gba", "rb").read()
GDIR = "src/data/graphic_table"
SYM = "gDynamicMotionGraphicOffsets"
VA = 0x088CC000
N = 209


def u32(o):
    return int.from_bytes(ROM[o:o + 4], "little")


def main():
    sp = f"{GDIR}/sprite_dynamic.s"
    lines = open(sp, encoding="utf-8").read().splitlines()
    mark = next(i for i, l in enumerate(lines) if "sets ===" in l)
    incp = f"{GDIR}/sprite_dynamic_body.inc"
    open(incp, "w", encoding="utf-8").write("\n".join(lines[mark:]) + "\n")

    o0 = VA - BASE
    L = []
    L.append("// Generated by tools/export_sprite_dynamic_gfx_c.py")
    L.append(f"// {SYM}[{N}] @ 0x{VA:08X} + inline sets + gfx bodies.")
    L.append("//")
    L.append("// NOTE: this .c is byte-identical to graphic_table/sprite_dynamic.s, but that")
    L.append("// .s is NOT byte-identical to ROM: the offset table + first set header match,")
    L.append("// yet the original export decoded the dynamic graphic-set bodies incorrectly")
    L.append("// (~85% of the body region diverges). Fixing that requires re-deriving the")
    L.append("// dynamic set structure in export_graphic_master.py, not a C transcription.")
    L.append("")
    L.append('#include "global.h"')
    L.append("")
    L.append(f"const u32 {SYM}[{N}] = {{")
    for r in range(0, N, 6):
        row = ", ".join("0x%08X" % u32(o0 + 4 * k)
                        for k in range(r, min(r + 6, N)))
        L.append(f"    {row},")
    L.append("};")
    L.append("")
    L.append("// inline Graphic sets + gfx bodies (remainder of the original .s)")
    L.append(f'__asm__(".section .rodata\\n.include \\"{incp}\\"\\n");')
    L.append("")
    open(f"{GDIR}/sprite_dynamic.c", "w", encoding="utf-8").write("\n".join(L))
    print(f"wrote {GDIR}/sprite_dynamic.c: {SYM}[{N}] + {incp}")


if __name__ == "__main__":
    main()
