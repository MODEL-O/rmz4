#!/usr/bin/env python
"""Generate src/data/tilesets.c (table-only C form of tilesets.s).

Mirrors the offset TABLE as a literal `const u32 gStageTilesetOffsets[26]`
(values read straight from ROM), then pulls each tileset's existing
header.inc body in via inline-asm `.include` (same data-include mechanism
rmz3's global.h uses). The per-tileset ColorGraphic descriptors + gfx bodies
stay in data/tilesets/tilesetNN/header.inc, exactly as tilesets.s referenced
them, so the assembled .rodata is byte-identical to the ROM region.

The .equiv flag aliases (MAP2D/LZ77/NO_PAL/BPP4) used inside the header.inc
files are re-declared via a leading inline-asm block, since the C TU has no
tilesets.s preamble.
"""

BASE = 0x08000000
ROM = open("Rockman Zero 4.gba", "rb").read()
TABLE = 0x08df2000
NENT = 26
INCDIR = "data/tilesets"


def u32(o):
    return int.from_bytes(ROM[o:o + 4], "little")


def main():
    t0 = TABLE - BASE
    ents = [u32(t0 + 4 * k) for k in range(NENT)]
    targets = [t0 + 4 * k + ents[k] for k in range(NENT)]
    ntileset = len(set(targets))

    L = []
    L.append("// Generated by tools/export_tilesets_c.py")
    L.append("// Table-only C form of src/data/tilesets.s; assembles "
             "byte-identical to")
    L.append(f"// ROM 0x{TABLE:08x} region. Per-tileset ColorGraphic headers + "
             "gfx bodies")
    L.append(f"// stay in {INCDIR}/tilesetNN/header.inc ({ntileset} unique "
             "tilesets).")
    L.append("")
    L.append("#include \"global.h\"")
    L.append("")
    L.append("// Flag aliases used inside the header.inc files (originally the")
    L.append("// .equiv preamble of tilesets.s).")
    L.append("__asm__(")
    L.append("    \".equiv MAP2D,  (1 << 0)\\n\"")
    L.append("    \".equiv LZ77,   (1 << 1)\\n\"")
    L.append("    \".equiv NO_PAL, (1 << 2)\\n\"")
    L.append("    \".equiv BPP4,   (1 << 5)\\n\");")
    L.append("")
    L.append("#define INCTILESET(inc) "
             "__asm__(\".section .rodata\\n.include \\\"\" inc \"\\\"\\n\")")
    L.append("")
    L.append("/*")
    L.append("  ColorGraphic* = &gStageTilesetOffsets[id] "
             "+ gStageTilesetOffsets[id]")
    L.append("*/")
    L.append(f"const u32 gStageTilesetOffsets[{NENT}] = {{")
    for r in range(0, NENT, 8):
        row = ", ".join(str(ents[k]) for k in range(r, min(r + 8, NENT)))
        L.append(f"    {row},")
    L.append("};")
    L.append("")
    for i in range(ntileset):
        L.append(f"INCTILESET(\"{INCDIR}/tileset{i:02d}/header.inc\");")
    L.append("")
    open("src/data/tilesets.c", "w", encoding="utf-8").write("\n".join(L))

    print(f"wrote src/data/tilesets.c: {NENT} stage offsets, "
          f"{ntileset} unique tilesets")


if __name__ == "__main__":
    main()
