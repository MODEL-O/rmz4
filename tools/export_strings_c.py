#!/usr/bin/env python
"""Generate C form of strings/strings.s (gStringData @ 0x0886d6b4).

strings.s uses charmap `.string "..."` literals that plain gas cannot assemble.
We encode each labelled run of strings to ROM bytes (text_lib.encode_string,
inverse of the decoder), validate every label against the ROM at its declared
address, then emit one `const u8 <label>[]` per label placed in its own named
section so verify_strings_c.py can link each at its ROM base and confirm
byte-identity. Run from rmz4-dev root.

NOTE: strings/dialogue_0887.s is intentionally NOT handled. Its header says it is
a lossy *readable* harvest (system charmap only; the 2-byte 0x0900 font excluded)
and it omits each conversation block's leading u16 offset table, so it is not a
byte-faithful representation of ROM and cannot be transcoded to byte-identical C.
"""
import re
import sys

import text_lib

BASE = 0x08000000
ROM = open("Rockman Zero 4.gba", "rb").read()
SDIR = "src/data/strings"

FILES = ["strings"]
LABEL_RE = re.compile(r"^(\w+)::\s*@\s*0x([0-9A-Fa-f]+)")


def parse(name):
    """Return [(label, addr, bytes)] for each labelled run of strings."""
    lines = open(f"{SDIR}/{name}.s", encoding="utf-8").read().splitlines()
    runs = []
    cur = None
    for l in lines:
        m = LABEL_RE.match(l)
        if m:
            cur = [m.group(1), int(m.group(2), 16), bytearray()]
            runs.append(cur)
            continue
        s = l.lstrip()
        if s.startswith('.string "'):
            q0 = l.index('"')
            q1 = l.rindex('"')
            cur[2] += text_lib.encode_string(l[q0 + 1:q1])
    return [(lab, addr, bytes(b)) for lab, addr, b in runs]


def validate(name, runs):
    ok = True
    for lab, addr, b in runs:
        o = addr - BASE
        if ROM[o:o + len(b)] != b:
            ok = False
            region = ROM[o:o + len(b)]
            for i in range(min(len(b), len(region))):
                if b[i] != region[i]:
                    print(f"  ENC FAIL {name} {lab} @0x{addr:08X} +0x{i:x}: "
                          f"got 0x{b[i]:02x} want 0x{region[i]:02x}")
                    break
            else:
                print(f"  ENC FAIL {name} {lab}: len {len(b)} vs "
                      f"region {len(region)}")
    return ok


def emit(name, runs):
    L = []
    L.append("// Generated by tools/export_strings_c.py")
    L.append(f"// charmap-encoded strings from strings/{name}.s; each label in its")
    L.append("// own named section, linked at its ROM base -> byte-identical to ROM.")
    L.append("")
    L.append('#include "global.h"')
    L.append("")
    for lab, addr, b in runs:
        L.append(f"// {lab} @ 0x{addr:08X} ({len(b)} bytes)")
        L.append(f'const u8 {lab}[] '
                 f'__attribute__((aligned(1), section(".rodata.gStringData"))) = {{')
        for r in range(0, len(b), 16):
            row = ", ".join("0x%02X" % x for x in b[r:r + 16])
            L.append(f"    {row},")
        L.append("};")
        L.append("")
    open(f"{SDIR}/{name}.c", "w", encoding="utf-8").write("\n".join(L))
    print(f"wrote {SDIR}/{name}.c: {len(runs)} labels")


def main():
    ok = True
    for name in FILES:
        runs = parse(name)
        if validate(name, runs):
            print(f"PASS  encoder vs ROM: {name} ({len(runs)} labels)")
        else:
            ok = False
        emit(name, runs)
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
