TERM = 0xFF


def decode_string(d, off, strict=False):
    """Decode one string starting at ROM offset `off` (no BASE).
    Returns (text, byte_length) or (None, -1) on failure.
    Handles escape prefixes F0/F3/F4/F5/F6 and the DA DC -> ✚ combo.
    """
    out = []
    i = off
    n = len(d)
    pre = None  # pending escape prefix
    while i < n:
        b = d[i]; i += 1
        if b == TERM:
            return ''.join(out), i - off
        if pre is None and b in (0xF0, 0xF3, 0xF4, 0xF5, 0xF6, 0xF7):
            pre = b
            continue
        if pre == 0xF0:
            out.append(CHARMAP_F0.get(b, f'{{F0 0x{b:02x}}}'))
            pre = None
            continue
        if pre == 0xF3:
            out.append(f'{{WINDOW 0x{b:02x}}}'); pre = None; continue
        if pre == 0xF4:
            out.append(f'{{ANSWER 0x{b:02x}}}'); pre = None; continue
        if pre == 0xF5:
            out.append(f'{{F5 0x{b:02x}}}'); pre = None; continue
        if pre == 0xF6:
            out.append(f'{{F6 0x{b:02x}}}'); pre = None; continue
        if pre == 0xF7:
            out.append(f'{{F7 0x{b:02x}}}'); pre = None; continue
        # DA DC -> plus
        if b == 0xDA and i < n and d[i] == 0xDC:
            out.append('✚'); i += 1; continue
        c = CHARMAP.get(b)
        if c is None:
            if strict:
                return None, -1
            out.append(f'{{?0x{b:02x}}}')
            continue
        out.append(c)
    return None, -1


def u16(d, o):
    return d[o] | (d[o + 1] << 8)


# ---- encoder (inverse of decode_string): charmap text -> ROM bytes ----
_CHAR2B = {k: v for k, v in _C2B.items() if not k.startswith('{')}
_F0_REV = {k: v for v, k in CHARMAP_F0.items()}   # kanji char -> F0 subbyte
_BRACE_PREFIX = {'WINDOW ': 0xF3, 'ANSWER ': 0xF4,
                 'F0 ': 0xF0, 'F5 ': 0xF5, 'F6 ': 0xF6, 'F7 ': 0xF7}


def encode_string(text):
    """Encode one charmap string (the literal inside `.string "..."`, including
    the trailing `$`) to ROM bytes. Inverse of decode_string."""
    out = bytearray()
    i, n = 0, len(text)
    while i < n:
        ch = text[i]
        if ch == '\\' and i + 1 < n:
            nxt = text[i + 1]
            if nxt == 'n':                  # gas escape: newline
                out.append(0xFC); i += 2; continue
            ch = nxt; i += 1                 # other gas escape (e.g. \" -> ")
            out.append(_CHAR2B[ch]); i += 1; continue
        if ch == '✚':
            out += b'\xDA\xDC'; i += 1; continue
        if ch == '{':
            j = text.index('}', i)
            inner = text[i + 1:j]
            tok = '{' + inner + '}'
            if tok in _C2B:
                out.append(_C2B[tok])
            elif inner.startswith('?'):                 # {?0xNN} raw byte
                out.append(int(inner[1:], 16))
            else:
                for pfx, code in _BRACE_PREFIX.items():
                    if inner.startswith(pfx):
                        out += bytes([code, int(inner[len(pfx):], 16)])
                        break
                else:
                    raise ValueError(f"unknown token {tok!r}")
            i = j + 1
            continue
        if ch in _CHAR2B:
            out.append(_CHAR2B[ch])
        elif ch in _F0_REV:
            out += bytes([0xF0, _F0_REV[ch]])
        else:
            raise ValueError(f"unmapped char {ch!r} (U+{ord(ch):04X})")
        i += 1
    return bytes(out)
