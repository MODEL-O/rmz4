#!/usr/bin/env python
"""Generate src/data/bgmaps.c (C form of bgmaps.s), byte-identical to ROM.

This mirrors export_bgmaps.py but emits a rmz3-style C file instead of asm.
The offset table is written as a literal `const u32 gBgMapOffsets[178]` whose
values are the exact self-relative offsets read straight from the ROM (C cannot
express `&BgMapHeaderN - &gBgMapOffsets[k]` as a constant initializer, so the
integers are baked in, exactly as rmz3 src/data/bgmaps.c does).

Each unique map becomes INC_BGMAP(n, w, h, "NNN.bin") -> a BgMapHeader struct
followed by INCBIN16 of data/bgmaps/NNN.bin (the same bins export_bgmaps.py
already wrote). The .c is self-contained (its own typedefs + macros) so it can
be assembled/verified with only arm-none-eabi-gcc.
"""
import os

BASE = 0x08000000
ROM = open("Rockman Zero 4.gba", "rb").read()
TABLE = 0x08b2c000
NENT = 178
BINDIR = "data/bgmaps"


def u16(o):
    return ROM[o] | (ROM[o + 1] << 8)


def u32(o):
    return int.from_bytes(ROM[o:o + 4], "little")


def main():
    t0 = TABLE - BASE
    ents = [u32(t0 + 4 * k) for k in range(NENT)]
    targets = [t0 + 4 * k + ents[k] for k in range(NENT)]
    uniq = sorted(set(targets))

    first_slot = {}
    for k, tg in enumerate(targets):
        first_slot.setdefault(tg, k)

    lw = u16(uniq[-1] + 4)
    lh = u16(uniq[-1] + 6)
    region_end = uniq[-1] + 8 + lw * lh * 2
    bounds = uniq + [region_end]
    sizes = {o: bounds[i + 1] - (o + 8) for i, o in enumerate(uniq)}

    L = []
    L.append("// Generated by tools/export_bgmaps_c.py")
    L.append("// C form of src/data/bgmaps.s; byte-identical to ROM "
             f"0x{TABLE:08x}..0x{region_end + BASE:08x}.")
    L.append(f"// gBgMapOffsets: {NENT} self-relative offsets, "
             f"{len(uniq)} unique maps ({NENT - len(uniq)} alias slots).")
    L.append("")
    L.append("#include \"global.h\"")
    L.append("")
    L.append(f"#define PATH(bin) \"{BINDIR}/\" bin")
    L.append("#define INC_BGMAP(n, w, h, bin)               \\")
    L.append("  const struct BgMapHeader BgMapHeader##n = { \\")
    L.append("      0x10001,                                \\")
    L.append("      w,                                      \\")
    L.append("      h,                                      \\")
    L.append("  };                                          \\")
    L.append("  INCBIN16(BgMap##n, PATH(bin))")
    L.append("")
    L.append("/*")
    L.append("  BgMapHeader = &gBgMapOffsets[idx] + gBgMapOffsets[idx]")
    L.append("*/")
    L.append(f"const u32 gBgMapOffsets[{NENT}] = {{")
    for r in range(0, NENT, 10):
        row = ", ".join(str(ents[k]) for k in range(r, min(r + 10, NENT)))
        L.append(f"    {row},")
    L.append("};")
    L.append("")
    for o in uniq:
        n = first_slot[o]
        w = u16(o + 4)
        h = u16(o + 6)
        note = ""
        if sizes[o] != w * h * 2:
            note = f"  // telescoped: bin={sizes[o]}B (shares tail w/ next map)"
        L.append(f"INC_BGMAP({n}, {w}, {h}, \"{n:03d}.bin\");"
                 f"  // 0x{o + BASE:08x}{note}")
    L.append("")
    open("src/data/bgmaps.c", "w", encoding="utf-8").write("\n".join(L))

    aliases = NENT - len(uniq)
    tele = sum(1 for o in uniq if sizes[o] != u16(o + 4) * u16(o + 6) * 2)
    print(f"wrote src/data/bgmaps.c: {NENT} slots, {len(uniq)} unique maps, "
          f"{aliases} aliases, {tele} telescoped")
    print(f"region VA 0x{uniq[0] + BASE:08x}..0x{region_end + BASE:08x} "
          f"(len 0x{region_end - (TABLE - BASE):x})")


if __name__ == "__main__":
    main()
